import assert from "node:assert/strict";
import { createServer } from "node:http";
import { readFile } from "node:fs/promises";
import { extname, resolve, sep } from "node:path";
import { fileURLToPath } from "node:url";
import { chromium } from "playwright";

const root=resolve(fileURLToPath(new URL("..",import.meta.url)));
function makeWav(){const samples=4410,buffer=Buffer.alloc(44+samples*2);buffer.write("RIFF",0);buffer.writeUInt32LE(36+samples*2,4);buffer.write("WAVE",8);buffer.write("fmt ",12);buffer.writeUInt32LE(16,16);buffer.writeUInt16LE(1,20);buffer.writeUInt16LE(1,22);buffer.writeUInt32LE(44100,24);buffer.writeUInt32LE(88200,28);buffer.writeUInt16LE(2,32);buffer.writeUInt16LE(16,34);buffer.write("data",36);buffer.writeUInt32LE(samples*2,40);for(let i=0;i<samples;i++)buffer.writeInt16LE(Math.round(Math.sin(2*Math.PI*440*i/44100)*5000),44+i*2);return buffer;}
const mime={".html":"text/html; charset=utf-8",".css":"text/css; charset=utf-8",".js":"text/javascript; charset=utf-8"};
const server=createServer(async(req,res)=>{try{let path=decodeURIComponent(new URL(req.url,"http://localhost").pathname);let relative=path==="/"?"index.html":path.slice(1);if(relative.endsWith("/"))relative+="index.html";const file=resolve(root,relative);if(file!==root&&!file.startsWith(root+sep))throw new Error("bad path");const body=await readFile(file);res.writeHead(200,{"content-type":mime[extname(file)]||"application/octet-stream"});res.end(body);}catch{res.writeHead(404);res.end("Not found");}});
const browser=await chromium.launch({headless:true,args:["--no-sandbox","--use-fake-device-for-media-stream","--use-fake-ui-for-media-stream"]});
try{
 await new Promise(resolveListen=>server.listen(0,"127.0.0.1",resolveListen));
 const origin="http://127.0.0.1:"+server.address().port;
 const context=await browser.newContext({viewport:{width:1280,height:900}});
 await context.grantPermissions(["microphone"],{origin});
 const page=await context.newPage();const errors=[];page.on("pageerror",e=>errors.push(e.message));
 const response=await page.goto(origin+"/apps/fx-lab/",{waitUntil:"domcontentloaded"});
 assert.equal(response.status(),200,"FX Lab loads");
 assert.equal(await page.locator(".module").count(),6,"FX Lab exposes six processing modules");
 await page.locator("#start-tone").click();
 await page.waitForFunction(()=>document.querySelector("#engine-state")?.textContent==="ENGINE READY");
 await page.waitForFunction(()=>document.querySelector("#peak-value")?.textContent!=="−∞ dB",null,{timeout:4000});
 assert.ok((await page.locator("#source-status").innerText()).includes("test tone"),"FX Lab starts a real oscillator source");
 await page.locator('[data-param="threshold"]').evaluate(el=>{el.value="-24";el.dispatchEvent(new Event("input",{bubbles:true}));});
 assert.equal(await page.locator("#threshold-value").innerText(),"-24 dB","Compressor threshold updates");
 await page.locator('[data-param="makeup"]').evaluate(el=>{el.value="3";el.dispatchEvent(new Event("input",{bubbles:true}));});
 assert.equal(await page.locator("#makeup-value").innerText(),"+3 dB","Compressor makeup gain updates");
 await page.waitForFunction(()=>document.querySelector("#gr-value")?.textContent!=="0.0 dB",null,{timeout:3000});
 await page.locator('[data-param="delayTime"]').evaluate(el=>{el.value="480";el.dispatchEvent(new Event("input",{bubbles:true}));});
 assert.equal(await page.locator("#delay-time-value").innerText(),"480 ms","Delay time updates");
 await page.locator('[data-bypass="compressor"]').click();
 assert.equal(await page.locator('[data-bypass="compressor"]').getAttribute("aria-pressed"),"true","Compressor bypass is stateful");
 await page.locator('[data-bypass="compressor"]').click();
 await page.locator('[data-preset="space"]').click();
 assert.equal(await page.locator("#decay-value").innerText(),"5.2 s","Preset updates reverb decay");
 await page.locator("#custom-preset-name").fill("My test chain");
 await page.locator("#save-preset").click();
 assert.ok((await page.locator("#saved-presets").innerText()).includes("My test chain"),"Custom preset saves locally");
 await page.locator('[data-param="delayTime"]').evaluate(el=>{el.value="100";el.dispatchEvent(new Event("input",{bubbles:true}));});
 await page.locator("#load-preset").click();
 assert.equal(await page.locator("#delay-time-value").innerText(),"520 ms","Saved preset restores all settings");
 const [presetDownload]=await Promise.all([page.waitForEvent("download"),page.locator("#export-preset").click()]);
 assert.ok(presetDownload.suggestedFilename().endsWith(".bzaudio-fx.json"),"Preset exports as a portable JSON file");
 const presetStream=await presetDownload.createReadStream();let presetText="";
 for await(const chunk of presetStream)presetText+=chunk.toString();
 const exportedPreset=JSON.parse(presetText);
 assert.equal(exportedPreset.format,"bzaudio-fx-preset","Preset export uses the documented format");
 exportedPreset.params.delayTime=610;
 await page.locator("#import-preset").setInputFiles({name:"imported.bzaudio-fx.json",mimeType:"application/json",buffer:Buffer.from(JSON.stringify(exportedPreset))});
 await page.locator("#load-preset").click();
 assert.equal(await page.locator("#delay-time-value").innerText(),"610 ms","Imported preset is validated and applied");
 await page.locator("#delete-preset").click();
 assert.ok(!(await page.locator("#saved-presets").innerText()).includes("My test chain"),"Custom preset can be deleted");
 await page.locator("#stop-audio").click();
 assert.ok((await page.locator("#source-status").innerText()).includes("Audio stopped"),"Stop control halts source");
 assert.deepEqual(errors,[],"FX Lab has no uncaught browser errors");
 await page.goto(origin+"/apps/bzaudio-id/",{waitUntil:"domcontentloaded"});
 await page.locator("#display-name").fill("Studio Test");
 await page.locator("#email").fill("studio@example.test");
 await page.locator("#role").selectOption({label:"Live sound engineer"});
 await page.locator("#profile-form button[type=submit]").click();
 assert.ok((await page.locator("#profile-status").innerText()).includes("not an authenticated"),"ID preview clearly disclaims authentication");
 await page.reload({waitUntil:"domcontentloaded"});
 assert.equal(await page.locator("#display-name").inputValue(),"Studio Test","Local ID profile restores after reload");
 await page.locator("#clear-profile").click();
 assert.equal(await page.locator("#display-name").inputValue(),"","BZaudio ID can clear local profile data");
 await page.reload({waitUntil:"domcontentloaded"});
 assert.equal(await page.locator("#display-name").inputValue(),"","Cleared BZaudio ID profile does not return after reload");
 assert.deepEqual(errors,[],"BZaudio ID has no uncaught browser errors");
 console.log("FX Lab audio engine and BZaudio ID profile browser smoke tests passed.");
}finally{await browser.close();server.close();}
