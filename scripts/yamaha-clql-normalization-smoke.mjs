import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import vm from "node:vm";
const source = readFileSync(new URL("../adapters/yamaha/clql-csv-normalization.js", import.meta.url), "utf8");
const context = vm.createContext({});
vm.runInContext(source, context);
const helper = context.BZAudioYamahaClQl;
assert.ok(helper);
assert.deepEqual({ ...helper.normalizeColour("GN") }, { value: "Green", recognized: true });
assert.deepEqual({ ...helper.normalizeColour("Black") }, { value: "Off", recognized: true });
assert.equal(helper.normalizeColour("chartreuse").recognized, false);
assert.equal(helper.normalizePortName("DNT 16").kind, "dante");
assert.equal(helper.normalizePortName("DANTE 16").channel, 16);
assert.equal(helper.normalizePortName("SL1 8").kind, "slot1");
assert.equal(helper.normalizePortName("Slot2 12").channel, 12);
assert.equal(helper.normalizePortName("MX 4").kind, "mix");
assert.equal(helper.normalizePortName("Mix Channel 4").channel, 4);
assert.equal(helper.normalizePortName("MT 3").kind, "matrix");
assert.equal(helper.normalizePortName("FX8B").side, "B");
assert.equal(helper.normalizePortName("PRFX 2 A").kind, "premium-rack");
assert.equal(helper.normalizePortName("NONE").kind, "none");
assert.equal(helper.normalizePortName("mystery").kind, "unknown");
console.log("Yamaha CL/QL CSV vocabulary normalizer tests passed.");
